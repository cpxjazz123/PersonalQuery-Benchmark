#!/usr/bin/env python3
"""Prepare stage1_filtered_users_reviews.json + 10 candidate query file
for gaussian_vades.py train. Reads Baby_Products_2023.jsonl.gz,
aggregates reviews per user, picks users with >=15 reviews,
extracts top-15 sentences per user (10 train + 5 holdout candidate queries).

Hardcoded config:
- CATEGORY = "Baby_Products"
- N_USERS = 300 (>=15 reviews filter, take first 300 by review count)
- SENTENCES_PER_USER = 10
- CANDIDATES_PER_USER = 10
- HOLDOUT_PER_USER = 5

Outputs (to /fs04/ar57/wenyu/PersoanlQuery/result/personal_query/<stage>/Baby_Products/):
- 01_preference_extraction/Baby_Products/stage1_filtered_users_reviews.json
- 12_complexity_analysis_clause_features/Baby_Products/query_10_candidates_clause_features_joint_fisher_shared_pca_k3.jsonl  (will be generated by gaussian_vades from raw)
- 06_query/Baby_Products/query_by_expression_style_no_depth_check_10.json
"""
from __future__ import annotations

import gzip
import json
import os
import random
import sys
from collections import defaultdict
from pathlib import Path

REPO_ROOT = Path("/fs04/ar57/wenyu/PersoanlQuery")
DATA_FILE = REPO_ROOT / "data" / "Baby_Products_2023.jsonl.gz"
CATEGORY = "Baby_Products"

STAGE1_DIR = REPO_ROOT / "result" / "personal_query" / "01_preference_extraction" / CATEGORY
QUERY_DIR = REPO_ROOT / "result" / "personal_query" / "06_query" / CATEGORY

STAGE1_FILE = STAGE1_DIR / "stage1_filtered_users_reviews.json"
RAW_QUERY_FILE = QUERY_DIR / "query_by_expression_style_no_depth_check_10.json"

MIN_REVIEWS_PER_USER = 15
N_USERS = 300
SENTENCES_PER_USER = 10
HOLDOUT_PER_USER = 5
RANDOM_SEED = 42


def main() -> None:
    random.seed(RANDOM_SEED)

    log = lambda msg: print(f"[prepare_inputs] {msg}", flush=True)
    log(f"读取 {DATA_FILE}")
    user_to_reviews: dict[str, list[dict]] = defaultdict(list)
    n_total = 0
    with gzip.open(DATA_FILE, "rt") as f:
        for line in f:
            n_total += 1
            row = json.loads(line)
            uid = row.get("user_id")
            if not uid or not row.get("text"):
                continue
            user_to_reviews[uid].append(row)

    log(f"扫描 {n_total} 评论, 共 {len(user_to_reviews)} 用户")

    eligible = [(uid, len(rs)) for uid, rs in user_to_reviews.items() if len(rs) >= MIN_REVIEWS_PER_USER]
    eligible.sort(key=lambda x: x[1], reverse=True)
    eligible = eligible[:N_USERS]
    log(f"筛选 >= {MIN_REVIEWS_PER_USER} 评论的用户, 取前 {N_USERS}: {len(eligible)} 用户")

    STAGE1_DIR.mkdir(parents=True, exist_ok=True)
    users_payload: list[dict] = []
    raw_query_payload: list[dict] = []
    skipped = 0
    for idx, (uid, nrev) in enumerate(eligible, start=1):
        reviews = user_to_reviews[uid]
        reviews_sorted = sorted(reviews, key=lambda r: r.get("timestamp", 0))
        kept_reviews = []
        seen_texts: set[str] = set()
        for review in reviews_sorted:
            text = (review.get("text") or "").strip()
            if not text or text in seen_texts:
                continue
            seen_texts.add(text)
            kept_reviews.append({"target_reviews": [text]})
            if len(seen_texts) >= SENTENCES_PER_USER + HOLDOUT_PER_USER:
                break

        if len(kept_reviews) < SENTENCES_PER_USER + HOLDOUT_PER_USER:
            skipped += 1
            continue

        users_payload.append(
            {
                "user_id": uid,
                "asin": kept_reviews[0].get("asin", ""),
                "reviews": kept_reviews,
                "review_count": len(kept_reviews),
            }
        )

        first_review = reviews_sorted[0]
        queries = []
        for r in kept_reviews[:SENTENCES_PER_USER]:
            txt = r["target_reviews"][0]
            queries.append(
                {
                    "query": txt,
                    "word_count": len(txt.split()),
                    "target_depth": None,
                    "user_avg_depth": None,
                    "attrs_used": None,
                }
            )
        raw_query_payload.append(
            {
                "user_id": uid,
                "asin": first_review.get("asin", ""),
                "expression_style_queries": queries,
            }
        )

        if idx % 50 == 0 or idx <= 5:
            log(f"  处理 {idx}/{len(eligible)}: user_id={uid}, 评论数={nrev}")

    log(f"完成: users={len(users_payload)}, skipped={skipped}")

    STAGE1_FILE.write_text(json.dumps(users_payload, ensure_ascii=False, indent=2), encoding="utf-8")
    log(f"已写入 {STAGE1_FILE}")

    QUERY_DIR.mkdir(parents=True, exist_ok=True)
    RAW_QUERY_FILE.write_text(json.dumps(raw_query_payload, ensure_ascii=False, indent=2), encoding="utf-8")
    log(f"已写入 {RAW_QUERY_FILE}")

    log(f"users={len(users_payload)}, candidates={len(raw_query_payload)}")


if __name__ == "__main__":
    main()
